const fs=require('node:fs');
const path=require('node:path');
const ts=require('../../../desktop/node_modules/typescript');
const root=path.resolve(__dirname,'../../..');
const file=path.join(root,'desktop/apps/desktop/electron/main.ts');
const source=fs.readFileSync(file,'utf8');
const sf=ts.createSourceFile(file,source,99,true);
const names=['createRuntimeLoginCallbacks','showLoginInstructions','promptForText','promptDataUrl','escapeHtml'];
const nodes=names.map(name=>{const n=sf.statements.find(n=>n.name?.text===name);if(!n)throw new Error(name);return n;});
const [create,instructions,prompt,dataUrl,escape]=nodes;
const text=n=>source.slice(n.pos,n.end);
const createText=text(create).replace('function createRuntimeLoginCallbacks(window?: BrowserWindow | null)', 'export function createRuntimeLoginCallbacks(\nresolveDialogWindow: (window?: BrowserWindow | null) => BrowserWindow | null | undefined,\nwindow?: BrowserWindow | null\n)');
const body=createText.slice(0,createText.lastIndexOf('}'))+text(instructions)+'\n'+text(prompt)+'\n}';
const tImport=sf.statements.find(n=>ts.isImportDeclaration(n)&&n.importClause?.namedBindings?.elements?.some(x=>x.name.text==='tMain'));
if(!tImport)throw new Error('tMain import not found');
let modulePath=tImport.moduleSpecifier.text;
modulePath=path.posix.relative('platform',modulePath).replaceAll('\\','/');
if(!modulePath.startsWith('.'))modulePath='./'+modulePath;
const target=path.join(path.dirname(file),'platform/login-prompts.ts');
if(fs.existsSync(target))throw new Error(target);
fs.writeFileSync(target,`import {BrowserWindow,shell} from "electron";\nimport {tMain} from ${JSON.stringify(modulePath)};\n`+body+'\n'+text(dataUrl)+'\n'+text(escape)+'\n');
let current=source;
for(const n of [...nodes].sort((a,b)=>b.pos-a.pos))current=current.slice(0,n.pos)+current.slice(n.end);
current=current.replace('createRuntimeLoginCallbacks(window)', 'createRuntimeLoginCallbacks(resolveDialogWindow, window)');
const direct='promptForText(mainWindow, message, placeholder ?? "", allowEmpty ?? false)';
if(!current.includes(direct))throw new Error('Direct prompt call not found');
current=current.replace(direct,'createRuntimeLoginCallbacks(resolveDialogWindow, mainWindow).onPrompt({message, placeholder: placeholder ?? "", allowEmpty: allowEmpty ?? false})');
fs.writeFileSync(file,'import {createRuntimeLoginCallbacks} from "./platform/login-prompts";\n'+current);
console.log('Login prompts moved with a window resolver; login callback and direct prompt callers wired.');

